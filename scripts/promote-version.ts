/**
 * The version half of a mobile promote: compute the next calver version and keep the four
 * places the shell names itself in lockstep, then move the platform web pin in the same act.
 *
 * 🚨 **Calver `YYYY.M.N`, the platform's and the desktop's scheme, numbered on this shell's
 * own line.** A phone app is distributed software rather than a hosted app, so semver is the
 * tempting choice; the date is the right one because a person reading a Releases page and an
 * installer comparing builds both only need "is this newer", and `YYYY.M.N` is valid semver
 * by design, so the Tauri bundler parses it without a translation layer.
 *
 * The rule: the first release of a month is `.0`, each later release in that month increments
 * the patch, and a month boundary rolls the month and resets to `.0`.
 *
 * ⚠️ **The four fields are why this is a script.** `package.json` is what the release workflow
 * reads (and what the release title claims), `tauri.conf.json` is what the app reports as its
 * own version, `Cargo.toml` is the crate's, and `Cargo.lock` is regenerated by any cargo build
 * and will happily carry a stale number back. Four hand-edited numbers are four chances to
 * disagree, and a disagreement ships silently: each tool reads its own copy and the build
 * succeeds against whichever one it found. `--check` (which CI runs) fails on any disagreement
 * before a tag can carry it.
 *
 * The baseline is `HEAD`'s four values, never the working tree's: an interrupted promote
 * already carries its own bump, and computing the next version from that double-bumps.
 *
 * The web pin is the same kind of number in a different currency: `anthersWeb` names the
 * promoted platform release the shell bundles, so a release that moved the shell's own version
 * while leaving the pin behind ships an old web app under a new number. `--web-pin` moves it,
 * and the promote command passes the platform's latest published tag.
 *
 * Usage:
 *   bun run scripts/promote-version.ts [--check] [--version YYYY.M.N] [--web-pin vYYYY.M.N]
 *
 * --check     validate the four fields' shape and agreement; write nothing. What CI runs.
 * --version   pin the next version instead of computing it, for a deliberate skip or overwrite.
 * --web-pin   move `anthersWeb` to the platform release this build must bundle.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

/** Every place the shell names its own version, with the line that carries it. */
export const FIELDS = [
	{ path: "package.json", pattern: /^(\t"version": ")[^"]+(",)$/m },
	{ path: "src-tauri/Cargo.toml", pattern: /^(version = ")[^"]+(")$/m },
	{ path: "src-tauri/tauri.conf.json", pattern: /^(\t"version": ")[^"]+(",)$/m },
	{
		path: "src-tauri/Cargo.lock",
		pattern: /^(\[\[package\]\]\nname = "anthers-mobile"\nversion = ")[^"]+(")$/m,
	},
] as const;

/** The platform release this shell bundles. Not a shell version, so it is compared apart. */
export const WEB_PIN = {
	path: "package.json",
	pattern: /^(\t"anthersWeb": ")[^"]+(",)$/m,
} as const;

export const CALVER = /^(\d{4})\.(\d{1,2})\.(\d+)$/;

/** A platform release tag: calver with the `v` every release here is tagged with. */
export const WEB_TAG = /^v\d{4}\.\d{1,2}\.\d+$/;

/** Any version-shaped value the fields might carry, calver or not. */
export const VERSION_SHAPE = /^\d+\.\d+\.\d+$/;

function fail(message: string): never {
	console.error(`promote-version: ${message}`);
	process.exit(1);
}

/**
 * The version one field's source text carries, or null when the pattern is missing.
 * The pattern wraps the value in two literals, so the version is what sits between them —
 * one read for a single line and for Cargo.lock's three-line block alike.
 */
export function readField(source: string, pattern: RegExp): string | null {
	const match = source.match(pattern);
	if (!match) return null;
	return match[0].slice(match[1].length, match[0].length - match[2].length);
}

/** Rewrite one field's source text to carry `version`. */
export function writeField(source: string, pattern: RegExp, version: string): string {
	return source.replace(pattern, (_all, before: string, after: string) => `${before}${version}${after}`);
}

/** The next calver version, given today's date and the current one. */
export function nextVersion(current: string, today = new Date()): string {
	const match = current.match(CALVER);
	if (!match) throw new Error(`"${current}" is not calver YYYY.M.N`);
	const thisYear = today.getFullYear();
	const thisMonth = today.getMonth() + 1;
	// Same month: count up. A new month: roll the month and reset. A pulled release
	// therefore never strands a number, because the count never skips forward.
	if (Number(match[1]) === thisYear && Number(match[2]) === thisMonth) {
		return `${thisYear}.${thisMonth}.${Number(match[3]) + 1}`;
	}
	return `${thisYear}.${thisMonth}.0`;
}

export type BumpPlan =
	| { action: "no-op"; target: string }
	| { action: "write"; target: string }
	| { action: "refuse"; target: string; committed: string; working: string };

/**
 * The bump decision, pure for the tests. `committed` is HEAD's version, `working` the
 * tree's — the same on a clean tree, the interrupted session's bump on a resumed one.
 */
export function bumpPlan(committed: string, working: string, pinned?: string, today?: Date): BumpPlan {
	const target = pinned ?? nextVersion(committed, today);
	if (target === working) return { action: "no-op", target };
	// A tree that agrees with neither HEAD nor this promote's target carries a value no
	// step of this flow wrote: refuse rather than overwrite, unless a pin says otherwise.
	if (working !== committed && pinned === undefined) {
		return { action: "refuse", target, committed, working };
	}
	return { action: "write", target };
}

/** One version across all four fields, or a failure naming each field's value. */
export function agreedVersion(read: (path: string) => string, label: string): string {
	const found = FIELDS.map(({ path, pattern }) => {
		const source = read(path);
		const version = readField(source, pattern);
		return { path, version };
	});
	const missing = found.filter((f) => f.version === null);
	if (missing.length) {
		fail(`${label}: no version line in ${missing.map((m) => m.path).join(", ")} — the field's shape changed.`);
	}
	const distinct = new Set(found.map((f) => f.version));
	if (distinct.size > 1) {
		fail(
			`${label}: the four version fields disagree (${found
				.map((f) => `${f.path}=${f.version}`)
				.join(", ")}). Which value is intended is a judgment this script does not own: ` +
				"restore them by hand and re-run, or pin one with --version YYYY.M.N.",
		);
	}
	const version = found[0].version as string;
	if (!VERSION_SHAPE.test(version)) fail(`${label}: "${version}" is not a version.`);
	return version;
}

/** The platform release the shell bundles, or a failure when the line has moved. */
export function webPin(read: (path: string) => string, label: string): string {
	const pin = readField(read(WEB_PIN.path), WEB_PIN.pattern);
	if (!pin) fail(`${label}: no anthersWeb line in ${WEB_PIN.path} — the field's shape changed.`);
	if (!WEB_TAG.test(pin)) fail(`${label}: anthersWeb carries "${pin}", which is not a vYYYY.M.N release tag.`);
	return pin;
}

/**
 * This promote's target: the pin when there is one, otherwise the next calver number.
 * 🚨 A pin is also how a line names itself deliberately, so the arithmetic is never the
 * only way in.
 */
function targetFor(committed: string, pinned?: string): string {
	if (pinned) return pinned;
	try {
		return nextVersion(committed);
	} catch {
		fail(
			`HEAD carries ${committed}, which is not calver, so there is no next number to compute. ` +
				"A release that starts a line names its own version: --version YYYY.M.N.",
		);
	}
}

function readTree(path: string): string {
	return readFileSync(path, "utf8");
}

function readHead(path: string): string {
	return execFileSync("git", ["show", `HEAD:${path}`], { encoding: "utf8" });
}

// ── the flow ─────────────────────────────────────────────────────────────────

function main(argv: string[]): void {
	const check = argv.includes("--check");
	const pinIndex = argv.indexOf("--version");
	const pinned = pinIndex === -1 ? undefined : argv[pinIndex + 1];
	const webIndex = argv.indexOf("--web-pin");
	const webTarget = webIndex === -1 ? undefined : argv[webIndex + 1];

	if (pinIndex !== -1 && (!pinned || !CALVER.test(pinned))) {
		fail(`--version needs a calver YYYY.M.N argument (got "${pinned ?? ""}").`);
	}
	if (webIndex !== -1 && (!webTarget || !WEB_TAG.test(webTarget))) {
		fail(`--web-pin needs a release tag argument like v2026.11.0 (got "${webTarget ?? ""}").`);
	}

	const committed = agreedVersion(readHead, "HEAD");
	const target = targetFor(committed, pinned);

	if (check) {
		agreedVersion(readTree, "the working tree");
		console.log(`✓ ${pinned ? `pinned ${pinned}` : `next is ${target}`} (HEAD carries ${committed})`);
		console.log(`✓ the web pin carries ${webPin(readTree, "the working tree")} (${WEB_PIN.path})`);
		return;
	}

	const working = agreedVersion(readTree, "the working tree");
	const plan = bumpPlan(committed, working, pinned);

	if (plan.action === "refuse") {
		fail(
			`the tree carries ${plan.working}, and HEAD carries ${plan.committed}: neither is this promote's ` +
				`target (${plan.target}). Restore the fields to ${plan.target} and re-run, or pin deliberately ` +
				"with --version YYYY.M.N.",
		);
	}

	if (plan.action === "no-op") {
		console.log(`✓ the tree already carries ${plan.target} — nothing to bump`);
	} else {
		for (const { path, pattern } of FIELDS) {
			const source = readTree(path);
			writeFileSync(path, writeField(source, pattern, plan.target));
		}
		console.log(`✓ ${committed} → ${plan.target} in all four fields`);
	}

	if (webTarget) {
		const current = webPin(readTree, "the working tree");
		if (current === webTarget) {
			console.log(`✓ the web pin already carries ${webTarget} — nothing to move`);
		} else {
			const source = readTree(WEB_PIN.path);
			writeFileSync(WEB_PIN.path, writeField(source, WEB_PIN.pattern, webTarget));
			console.log(`✓ web pin ${current} → ${webTarget}`);
		}
	} else {
		console.log(`✓ the web pin carries ${webPin(readTree, "the working tree")}, left alone`);
	}

	console.log(`\nnext:\n  git tag v${plan.target}\n  git push origin v${plan.target}`);
}

if (import.meta.main) main(process.argv.slice(2));
